"""tor configuration and process supervision."""
from __future__ import annotations

import ipaddress
import os
import re
import time
from pathlib import Path
from typing import Callable
from urllib.parse import urlsplit

from .config import Settings
from .osinfo import LINUX
from .paths import Layout
from .winutil import spawn_detached, tail_files

LYREBIRD_TRANSPORTS = ("meek_lite", "obfs2", "obfs3", "obfs4", "scramblesuit", "webtunnel")
SNOWFLAKE_TRANSPORTS = ("snowflake",)
_BOOT_RE = re.compile(r"Bootstrapped (\d{1,3})%")


class TorConfigError(ValueError):
    pass


class TorError(RuntimeError):
    pass


def tor_path(path: Path) -> str:
    """torrc values are whitespace-split, so paths must not contain spaces/quotes/#.
    Windows drive paths keep native backslashes: tor treats 'C:/x' as relative and warns."""
    text = Path(path).as_posix()
    if re.match(r"^[A-Za-z]:/", text):
        text = text.replace("/", "\\")
    elif "\\" in text:
        raise TorConfigError(f"path not usable in torrc: {text}")
    if re.search(r'[\s"#]', text):
        raise TorConfigError(f"path not usable in torrc (spaces/quotes): {text}")
    return text


def normalize_bridge(line: str) -> str:
    line = line.strip()
    if not line:
        raise TorConfigError("empty bridge line")
    if any(ord(c) < 32 or c in '"\\#' for c in line):
        raise TorConfigError("bridge line contains forbidden characters")
    parts = line.split()
    if parts[0].lower() == "bridge":
        parts = parts[1:]
    if not parts:
        raise TorConfigError("empty bridge line")
    first = parts[0]
    if first not in LYREBIRD_TRANSPORTS + SNOWFLAKE_TRANSPORTS and not _is_addr_port(first):
        raise TorConfigError(f"unknown bridge transport: {first}")
    return " ".join(parts)


def _is_addr_port(token: str) -> bool:
    host, sep, port = token.rpartition(":")
    if not sep or not port.isdigit() or not 0 < int(port) < 65536:
        return False
    try:
        ipaddress.ip_address(host.strip("[]"))
        return True
    except ValueError:
        return False


def bridge_lines(settings: Settings) -> list[str]:
    return [normalize_bridge(b) for b in settings.bridges if b.strip()]


def bridge_transports(lines: list[str]) -> set[str]:
    return {l.split()[0] for l in lines if not _is_addr_port(l.split()[0])}


def bridge_domains(lines: list[str]) -> list[str]:
    """Hostnames a pluggable transport must resolve itself (broker, fronts, STUN, webtunnel)."""
    hosts: set[str] = set()
    for line in lines:
        for token in line.split()[1:]:
            key, sep, value = token.partition("=")
            if not sep:
                continue
            if key == "url":
                hosts.add(urlsplit(value).hostname or "")
            elif key in ("front", "fronts"):
                hosts.update(value.split(","))
            elif key == "ice":
                for server in value.split(","):
                    # stun:host:port
                    pieces = server.split(":")
                    if len(pieces) >= 2:
                        hosts.add(pieces[1])
    clean = set()
    for h in hosts:
        h = h.strip().lower().rstrip(".")
        if not h or not re.fullmatch(r"[a-z0-9.-]{1,253}", h):
            continue
        try:
            ipaddress.ip_address(h)
            continue
        except ValueError:
            clean.add(h)
    return sorted(clean)


def build_torrc(settings: Settings, layout: Layout) -> str:
    lines = [
        "# Generated by PhantomX on every start. Edits are overwritten.",
        f"DataDirectory {tor_path(layout.tor_data)}",
        # strict: new circuit per destination (slow to open sites). balanced: shared circuits,
        # rotated by tor every MaxCircuitDirtiness (10 min).
        f"SocksPort 127.0.0.1:{settings.socks_port}"
        + (" IsolateDestAddr IsolateDestPort" if settings.privacy_mode == "strict" else ""),
        "SocksPolicy accept 127.0.0.1",
        "SocksPolicy reject *",
        f"DNSPort 127.0.0.1:{settings.dns_port}",
        f"ControlPort 127.0.0.1:{settings.control_port}",
        "CookieAuthentication 1",
        f"CookieAuthFile {tor_path(layout.cookie)}",
        f"Log notice file {tor_path(layout.tor_log)}",
        "SafeLogging 1",
        "AvoidDiskWrites 1",
        "ClientOnly 1",
        "ClientUseIPv6 0",
    ]
    if layout.geoip.exists():
        lines.append(f"GeoIPFile {tor_path(layout.geoip)}")
    if layout.geoip6.exists():
        lines.append(f"GeoIPv6File {tor_path(layout.geoip6)}")
    if settings.use_bridges:
        bridges = bridge_lines(settings)
        if not bridges:
            raise TorConfigError("use_bridges is on but there are no bridge lines")
        transports = bridge_transports(bridges)
        lines.append("UseBridges 1")
        if transports & set(LYREBIRD_TRANSPORTS):
            if not layout.lyrebird_exe.exists():
                raise TorConfigError("lyrebird.exe not found in the installed tor bundle")
            lines.append(f"ClientTransportPlugin {','.join(LYREBIRD_TRANSPORTS)} exec {tor_path(layout.lyrebird_exe)}")
        if transports & set(SNOWFLAKE_TRANSPORTS):
            # Tor 0.4.9 / bundle 16.x ships snowflake inside lyrebird.exe; older bundles had snowflake-client.exe.
            exe = layout.snowflake_exe if layout.snowflake_exe.exists() else layout.lyrebird_exe
            if not exe.exists():
                raise TorConfigError("no snowflake-capable transport (lyrebird.exe) in the installed tor bundle")
            lines.append(f"ClientTransportPlugin snowflake exec {tor_path(exe)}")
        lines += [f"Bridge {b}" for b in bridges]
    return "\n".join(lines) + "\n"


def parse_progress(text: str) -> tuple[int, str | None]:
    pct = max((int(m) for m in _BOOT_RE.findall(text)), default=0)
    err = None
    for line in text.splitlines():
        if "[err]" in line:
            err = line.strip()
    return min(pct, 100), err


class TorService:
    def __init__(self, layout: Layout, spawn: Callable = spawn_detached):
        self.layout = layout
        self.spawn = spawn

    def prepare(self, torrc: str) -> None:
        self.layout.run.mkdir(parents=True, exist_ok=True)
        self.layout.tor_data.mkdir(parents=True, exist_ok=True)
        self.layout.torrc.write_text(torrc, encoding="utf-8")
        self.layout.torrc_defaults.write_text("", encoding="utf-8")
        self.layout.tor_log.write_text("", encoding="utf-8")

    def start(self) -> int:
        return self.spawn(
            [self.layout.tor_exe, "--defaults-torrc", self.layout.torrc_defaults, "-f", self.layout.torrc],
            cwd=self.layout.tor_dir, output=self.layout.tor_console, env=self._env(),
        )

    def _env(self) -> dict | None:
        if self.layout.os != LINUX:
            return None
        env = dict(os.environ)  # the Linux bundle ships its own libssl/libevent next to tor
        env["LD_LIBRARY_PATH"] = str(self.layout.tor_dir)
        return env

    def read_progress(self) -> tuple[int, str | None]:
        try:
            return parse_progress(self.layout.tor_log.read_text(encoding="utf-8", errors="replace"))
        except FileNotFoundError:
            return 0, None

    def log_tail(self, n: int = 6) -> str:
        return tail_files([self.layout.tor_log, self.layout.tor_console], n)

    def wait_bootstrap(self, timeout: float, is_alive: Callable[[], bool],
                       on_progress: Callable[[int], None] = lambda p: None,
                       sleep: Callable[[float], None] = time.sleep,
                       clock: Callable[[], float] = time.monotonic) -> None:
        deadline = clock() + timeout
        last = -1
        polls = 0
        while True:
            pct, err = self.read_progress()
            if pct != last:
                last = pct
                on_progress(pct)
            if pct >= 100:
                return
            if err:
                raise TorError(f"tor error: {err}")
            polls += 1
            if polls % 4 == 0 and not is_alive():
                raise TorError("tor exited unexpectedly:\n" + self.log_tail())
            if clock() >= deadline:
                raise TorError(f"tor did not finish connecting within {int(timeout)}s (stuck at {pct}%). "
                               "If Tor is blocked in your country, enable bridges.")
            sleep(0.5)
